let current: Lang = 'en';
const listeners = new Set<() => void>();
export const getLang = (): Lang => current;
export const setLang = (lang: Lang): void => {
  const next = lang === 'zh' ? 'zh' : 'en';
  if (next === current) return;
  current = next;
  listeners.forEach((notify) => notify());
};
export const t = (text: string): string => (current === 'zh' ? (ZH[text] ?? text) : text);
// Only components that need the language *value* - the switcher, and the text studio defaulting
// its output language - need this. Everything that just prints translated text calls t().
export function useLang(): Lang {
  return useSyncExternalStore(
    (notify) => { listeners.add(notify); return () => { listeners.delete(notify); }; },
    getLang,
    getLang
  );
}
